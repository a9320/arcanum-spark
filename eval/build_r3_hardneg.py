def _item(iid, title, vuln_type, file_path, attack_path, confidence,
          *, echo, new_file, evidence, in_final, gate, note):
    return {
        "id": iid, "origin": "synthetic", "title": title, "vuln_type": vuln_type,
        "file_path": file_path, "attack_path": attack_path, "confidence": confidence,
        "heuristics": {"echo_of_baseline": echo, "duplicate_of": None, "degenerate": False,
                       "evidence_backed": evidence, "new_file_vs_baseline": new_file},
        "pipeline": {"verdict": "", "verification_method": "", "confidence": "",
                     "in_final": in_final, "join_method": "none"},
        "label": {"gate": gate, "source": EXAM_VERSION, "note": note},
    }


def build_r3_hardneg() -> dict:
    baseline_rows = [
        {"file": f, "rule": r, "title": t, "severity": s, "has_decoded_payload": d}
        for f, r, t, s, d in exam.BASELINE
    ]
    items: list[dict] = []
    pair = 0
    for m_i, mech in enumerate(_MECHS):
        for t_i, title in enumerate(mech["titles"]):
            for i2 in range(2):
                pair += 1
                s = (m_i * 2 + t_i * 2 + i2) % 4
                app, ek, eb = _APPS[s], _EK[s], _EB[s]
                inj, benign = _INJ[s], _BENIGN[s]
                slots = {"app": app, "APPUP": app.upper(), "ek": ek, "eb": eb,
                         "inj": inj, "benign": benign}
                fk, fb = mech["kfile"].format(**slots), mech["bfile"].format(**slots)
                items.append(_item(
                    f"TWIN-K{pair:02d}", title.format(**slots), mech["type"], fk,
                    mech["ktpl"].format(**slots), "high", echo=None, new_file=True,
                    evidence=False, in_final=True, gate="KEEP",
                    note=f"boundary_pair:train:{mech['anchor']}"))
                items.append(_item(
                    f"TWIN-B{pair:02d}", title.format(**slots), mech["type"], fb,
                    mech["btpl"].format(**slots), "medium", echo=None, new_file=True,
                    evidence=False, in_final=False, gate="PRUNE",
                    note=f"self-refuting(train): {mech['breason']}"))

    for i, (row_i, title, path) in enumerate(_PARA, start=1):
        f, r, _t, _s, _d = exam.BASELINE[row_i]
        items.append(_item(
            f"PARA-T{i:02d}", title, r, f, path, "high",
            echo={"rule": r, "match": "exact_file_type"}, new_file=False,
            evidence=False, in_final=True, gate="PRUNE",
            note="echo_exact(paraphrased, train instance)"))

    for i in range(12):
        vt, tt = _EVID_TYPES[i % 4], _EVID_TITLES[i % 4]
        s = i % 4
        path = _EVID_PATHS[i % 3].format(inj=_INJ[s], ek=_EK[s])
        items.append(_item(
            f"EVID-T{i + 1:02d}", tt, vt, exam._EVIDENCE_FILE, path, "high",
            echo=None, new_file=False, evidence=True, in_final=True, gate="KEEP",
            note="evidence_backed (decoded_payload reproduced; semantic type != baseline rule)"))

    return {
        "schema": SCHEMA,
        "created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "source": {
            "generator": EXAM_VERSION,
            "baseline_from": "eval/expected.json agent0_required (QB-S1 registry, 同 build_hard_exam)",
            "families": {"twin_pairs": pair, "paraphrase_echo": len(_PARA),
                         "evidence_keep": 12},
            "labels": "by construction; 同型不同实例——难卷 23 条本体 held-out 不复现"
                      "（anti-leak 断言见 tests/test_r3_hardneg.py）",
            "purpose": "R3 训练补充：补自驳 benign-twin/换措辞回显/echo-shape 证据 KEEP 三类训练分布缺口"
                       "（病灶判读=WORK_LOG 2026-09-28 20:27 区块）",
        },
        "n_baseline": len(baseline_rows),
        "baseline_rows": baseline_rows,
        "items": items,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description="R3 难负训练实例构造器（同型异实例，零 LLM、确定性）")
    ap.add_argument("-o", "--out", default="gate_dataset_r3hardneg.json", help="输出 dataset 路径")
    args = ap.parse_args()
    dataset = build_r3_hardneg()
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(dataset, ensure_ascii=False, indent=2), encoding="utf-8")
    fam = dataset["source"]["families"]
    n_keep = sum(1 for it in dataset["items"] if it["label"]["gate"] == "KEEP")
    print(f"[r3-hardneg] {len(dataset['items'])} items（TWIN {fam['twin_pairs']} 对"
          f" + PARA {fam['paraphrase_echo']} + EVID {fam['evidence_keep']}）"
          f"KEEP {n_keep} / PRUNE {len(dataset['items']) - n_keep} → {out}")
    print(f"  src（切分原子）= {out.parent.name}；R3 export 时并入 --dataset 即可")
    return 0


if __name__ == "__main__":
    sys.exit(main())
